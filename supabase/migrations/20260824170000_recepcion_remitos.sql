-- Recepción colaborativa de remitos y cierre integrado con pedidos entre locales.

create table if not exists public.op_local_aliases (
  alias text primary key,
  local_nombre text not null,
  created_at timestamptz not null default now()
);

insert into public.op_local_aliases(alias,local_nombre)
select 'Bloqueo Punta del Este','Punta del Este'
where exists(select 1 from public.locales where nombre='Punta del Este')
on conflict(alias) do update set local_nombre=excluded.local_nombre;

create table if not exists public.op_recepciones (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  numero_remito text not null,
  fecha_remito date not null,
  origen_local text not null,
  destino_local text not null,
  estado text not null default 'en_control' check (estado in ('en_control','cerrado','archivado')),
  original_filename text,
  original_path text,
  import_meta jsonb not null default '{}'::jsonb,
  observaciones_cierre text,
  created_by uuid not null references public.perfiles(id),
  closed_by uuid references public.perfiles(id),
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(numero_remito,fecha_remito,origen_local,destino_local)
);

create table if not exists public.op_recepcion_items (
  recepcion_id uuid not null references public.op_recepciones(id) on delete cascade,
  codigo text not null,
  nombre text not null,
  descripcion_archivo text,
  barras text,
  marca text,
  esperado integer not null check (esperado > 0),
  recibido integer not null default 0 check (recibido >= 0),
  no_recibido boolean not null default false,
  observacion text,
  source_lines jsonb not null default '[]'::jsonb,
  updated_by uuid references public.perfiles(id),
  updated_by_name text,
  updated_at timestamptz not null default now(),
  primary key(recepcion_id,codigo)
);

create table if not exists public.op_recepcion_extras (
  recepcion_id uuid not null references public.op_recepciones(id) on delete cascade,
  codigo text not null,
  nombre text not null,
  barras text,
  cantidad integer not null default 0 check (cantidad >= 0),
  observacion text,
  updated_by uuid references public.perfiles(id),
  updated_by_name text,
  updated_at timestamptz not null default now(),
  primary key(recepcion_id,codigo)
);

create table if not exists public.op_recepcion_participantes (
  recepcion_id uuid not null references public.op_recepciones(id) on delete cascade,
  usuario_id uuid not null references public.perfiles(id),
  nombre text not null,
  joined_at timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  primary key(recepcion_id,usuario_id)
);

create table if not exists public.op_recepcion_eventos (
  id bigint generated by default as identity primary key,
  recepcion_id uuid not null references public.op_recepciones(id) on delete cascade,
  usuario_id uuid references public.perfiles(id),
  usuario_nombre text,
  accion text not null,
  codigo text,
  detalle jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.op_recepcion_pedidos (
  recepcion_id uuid not null references public.op_recepciones(id) on delete cascade,
  pedido_id uuid not null references public.pedidos(id),
  coincidencia text not null default 'ruta_sku' check (coincidencia in ('remito','despacho','ruta_sku')),
  linked_at timestamptz not null default now(),
  primary key(recepcion_id,pedido_id)
);

